import { z } from "zod";
const id = z.string().trim().min(1).max(200).regex(/^[A-Za-z0-9][A-Za-z0-9._:-]*$/);
const integer = z.number().int().nonnegative().max(2147483647);
export const CardIdSchema = id.brand<"CardId">();
export const CardRevisionSchema = integer.positive().brand<"CardRevision">();
export const RulesetIdSchema = id.brand<"RulesetId">();
export const RulesetVersionSchema = id.brand<"RulesetVersion">();
export const PlayerIdSchema = z.uuid().brand<"PlayerId">();
export const MatchIdSchema = z.uuid().brand<"MatchId">();
export const DeckIdSchema = z.uuid().brand<"DeckId">();
export const CommandIdSchema = z.uuid().brand<"CommandId">();
export const GameStateVersionSchema = integer.brand<"GameStateVersion">();
export const GameEventSequenceSchema = integer.brand<"GameEventSequence">();
export type CardId = z.infer<typeof CardIdSchema>;
export type CardRevision = z.infer<typeof CardRevisionSchema>;
export type RulesetId = z.infer<typeof RulesetIdSchema>;
export type RulesetVersion = z.infer<typeof RulesetVersionSchema>;
export type PlayerId = z.infer<typeof PlayerIdSchema>;
export type MatchId = z.infer<typeof MatchIdSchema>;
export type DeckId = z.infer<typeof DeckIdSchema>;
export type CommandId = z.infer<typeof CommandIdSchema>;
export type GameStateVersion = z.infer<typeof GameStateVersionSchema>;
export type GameEventSequence = z.infer<typeof GameEventSequenceSchema>;
export const CardPrintingIdSchema = id.brand<"CardPrintingId">();
export const CardInstanceIdSchema = id.brand<"CardInstanceId">();
export const GigInstanceIdSchema = id.brand<"GigInstanceId">();
export type CardPrintingId = z.infer<typeof CardPrintingIdSchema>;
export type CardInstanceId = z.infer<typeof CardInstanceIdSchema>;
export type GigInstanceId = z.infer<typeof GigInstanceIdSchema>;
